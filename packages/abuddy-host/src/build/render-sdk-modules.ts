// Renders the host pack loader's bridge module (src/packs/runtime/sdk-modules.ts): a static import of
// every shared-instance package export pack runtime code can require, so the app bundle includes them
// and pack code gets the bundle's instances. `npm run sdk-modules:update -w @abuddy/host` writes it;
// tests/packs/runtime/sdk-bridge-drift.spec.ts fails when it's stale.
import {
  SHARED_INSTANCE_PACKAGES, sharedInstanceExports, sharedInstanceSpecifiers,
} from './shared-deps.ts';

/** Shared-instance exports the app doesn't bridge: pack runtime code never requires them */
export const APP_UNBRIDGED: Readonly<Record<string, string>> = {
  // Inlined into seed action strings at compile time; the sandbox that runs them has no module loader
  '@abuddy/sdk/actions': 'compile-time only, inlined into seed strings',
  // A pack's unit tests (through @abuddy/testing) load it, never a pack's runtime in the app
  '@abuddy/sdk/testing': 'unit-test runtime only',
  // A pack directory on disk, for the specs whose subject is pack tooling. Source-only: the entry has no
  // published target and a pack's config may not declare the condition, so no pack can resolve it at all
  '@abuddy/sdk/testing/pack-fixture': 'repo test tooling, resolvable only under @abuddy/source',
  // What each value-serialising pass answers, as data three suites assert their own rows against. Source-only
  // for the same reason: it is this repo's test data about this repo's code, and no pack has a row in it
  '@abuddy/sdk/testing/serialisation-matrix': 'repo test data, resolvable only under @abuddy/source',
};

/** The shared-instance specifiers the app bridges, from each package's exports map as `fromFile` resolves it */
export function appBridgedSpecifiers(fromFile: string): string[] {
  return SHARED_INSTANCE_PACKAGES
    .flatMap((pkg) => sharedInstanceSpecifiers(pkg, sharedInstanceExports(pkg, fromFile)))
    .filter((specifier) => !(specifier in APP_UNBRIDGED))
    .sort();
}

export function renderSharedModules(fromFile: string): string {
  const specifiers = appBridgedSpecifiers(fromFile);
  const name = (specifier: string) => `_${specifier.replace(/^@/, '').replace(/[^a-zA-Z0-9]+/g, '_')}`;
  return [
    '// Generated by `npm run sdk-modules:update -w @abuddy/host` from SHARED_INSTANCE_PACKAGES',
    '// (../../build/shared-deps.ts) and each package\'s exports map. Do not edit.',
    ...specifiers.map((specifier) => `import * as ${name(specifier)} from '${specifier}';`),
    '',
    '/** Every shared-instance export pack runtime code can require, keyed by specifier */',
    'export const SHARED_INSTANCE_MODULES: Readonly<Record<string, unknown>> = {',
    ...specifiers.map((specifier) => `  '${specifier}': ${name(specifier)},`),
    '};',
    '',
  ].join('\n');
}
