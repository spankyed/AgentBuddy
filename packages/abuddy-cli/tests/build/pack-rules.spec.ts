import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it } from 'vitest';
import { loadPackChecks, packRuleProblems, PACK_RULES, refusePackRuleViolations, type PackRuleKey } from '../../src/build/pack-rules.ts';
import { resetSourceCache } from '../../src/build/pack-sources.ts';

/**
 * src/build/pack-rules.ts: the rules every pack is held to, which `abuddy build`, `abuddy validate` and
 * `abuddy test` run. The repo's own packs go through the same functions from
 * `scripts/check-import-specifiers.ts`; this is every other pack.
 */
const dirs: string[] = [];
afterEach(() => {
  for (const dir of dirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
  // The reader caches by path, and a temp tree reuses paths
  resetSourceCache();
});

/** A pack directory holding `files`, each written under it */
function pack(files: Record<string, string>): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'abuddy-pack-rules-'));
  dirs.push(dir);
  for (const [file, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    fs.writeFileSync(path.join(dir, file), content);
  }
  return dir;
}

/** One rule's findings, by key, over a pack's `src` */
const problems = (dir: string, key: PackRuleKey): string[] => packRuleProblems(dir).get(key) ?? [];

describe('internal-package-imports', () => {
  it.each([
    ['src/system.ts', "import { _getMediaPath } from '@abuddy/sdk/utils';\n", 'src/system.ts:1: _getMediaPath from @abuddy/sdk/utils'],
    ['src/probe.ts', "const { _seedHookRegistry } = await import('@abuddy/sdk/seed');\n", 'src/probe.ts:1: _seedHookRegistry from @abuddy/sdk/seed'],
    ['src/panel.vue', "<template><div /></template>\n<script setup lang=\"ts\">\nimport { _rootEvents as bus } from '@abuddy/sdk/runtime';\n</script>\n", 'src/panel.vue:3: _rootEvents from @abuddy/sdk/runtime'],
  ])('refuses %s', (file, content, problem) => {
    expect(problems(pack({ [file]: content }), 'internal-package-imports')).toEqual([problem]);
  });

  it('accepts public API, a pack-local underscore and the generated facades', () => {
    const dir = pack({
      'src/system.ts': [
        "import { importCompiledSeeds, getDataDirPath } from '@abuddy/sdk/utils';",
        "import { formatProviderError as _formatProviderError } from '@abuddy/sdk/actions';",
        "import { _fmt } from './_helpers/format.ts';",
        '',
      ].join('\n'),
      // Generated by the pack's own build, from the manifest: not the author's to fix
      'src/__generated__/events.ts': "import { _rootEvents } from '@abuddy/sdk/runtime';\n",
    });
    expect(problems(dir, 'internal-package-imports')).toEqual([]);
  });

  it('has nothing to say about a pack with no src', () => {
    expect([...packRuleProblems(pack({ 'abuddy.json': '{}' }))]).toEqual([]);
  });
});

/**
 * One rule, one offending file, one expected message. The table *is* the coverage claim below, so a rule added
 * without a row here fails that case — where the set it replaced could be satisfied by editing the set.
 */
const FIRES_ON_A_FILE: [PackRuleKey, string, string][] = [
    ['own-modules', "import { sendToSystem } from '#generated/events';\n",
      "src/f.ts:1: '#generated/events' names no file — write '#generated/events.ts'"],
    // The `.js` form is this rule's too, not a second rule's: one offence, one message, and this one names the fix
    ['own-modules', "import { sibling } from './sibling.js';\n",
      "src/f.ts:1: './sibling.js' names no file — write './sibling.ts'"],
    ['pack-own-aliases', "import { x } from '@/features/notes/be/x.ts';\n", 'src/f.ts:1: @/features/notes/be/x.ts'],
    ['host-imports', "import { edgeStore } from '@abuddy/host/ears';\n", 'src/f.ts:1: @abuddy/host/ears'],
    ['lmdb-imports', "import { open } from 'lmdb';\n", 'src/f.ts:1: lmdb'],
    ['untyped-sends', "import { untypedSendToSystem } from '@abuddy/sdk/events';\n",
      'src/f.ts:1: untypedSendToSystem from @abuddy/sdk/events'],
    ['raw-transport', 'export const send = () => _rootEvents.emitOutgoing(event);\n', 'src/f.ts:1: _rootEvents'],
];

/**
 * The rules whose firing case cannot be a row above, and the title of the case that covers each.
 *
 * The title is checked against this file's own text, so an entry pointing at a case that was renamed or
 * deleted fails rather than standing as a claim nobody re-reads — the same reason every exception table in this
 * repo reports one that has stopped applying.
 */
const FIRES_ELSEWHERE: Record<string, string> = {
  // Two shapes and eleven allowed ones, transcribed when the repo script's console rule moved here
  'backend-console': 'backend-console fires under a backend path and not under a frontend one',
  // A `_`-prefixed import from an @abuddy package, which needs no pack fixture to be offending
  'internal-package-imports': "internal-package-imports",
  // Not a file's text but the pack's own module resolution, so its case needs a whole installed package to
  // resolve against
  'source-resolution': 'source-resolution',
  // A feature layout, which one `src/f.ts` cannot express: the offence is which feature the file is in
  'cross-feature-imports': "cross-feature-imports flags another feature's frontend and allows a feature its own",
  // The pack as a whole: which module is a contract comes from the manifest, so its case needs one
  'contract-leaves': 'contract-leaves flags a contract leaf that reaches its own machine',
};

/**
 * One firing example per rule, so none of them can land without a case that proves it bites — the same
 * property `check:specifiers`' own spec asserts for the repo's rules. The pack fixture carries the
 * `package.json` `imports` map that makes a `#` string a specifier rather than a colour.
 */
describe('every rule', () => {
  /** A pack with an imports map, a generated facade to resolve against, and whatever else the case writes */
  const packWithImports = (files: Record<string, string>) => pack({
    'package.json': JSON.stringify({ name: 'p', type: 'module', imports: { '#generated/*': './src/__generated__/*' } }),
    'src/__generated__/events.ts': 'export const sendToSystem = 1;\n',
    'src/sibling.ts': 'export const sibling = 1;\n',
    ...files,
  });

  it.each(FIRES_ON_A_FILE)('%s fires on an offending file', (key, code, problem) => {
    expect(problems(packWithImports({ 'src/f.ts': code }), key as PackRuleKey)).toEqual([problem]);
  });

  it('backend-console fires under a backend path and not under a frontend one', () => {
    const dir = packWithImports({
      'src/features/notes/be/system.ts': "console.log('x');\n",
      'src/features/notes/fe/state.ts': "console.log('x');\n",
    });
    expect(problems(dir, 'backend-console')).toEqual(['src/features/notes/be/system.ts:1: console.log']);
  });

  it("cross-feature-imports flags another feature's frontend and allows a feature its own", () => {
    const dir = packWithImports({
      'package.json': JSON.stringify({ name: 'p', type: 'module', imports: { '#generated/*': './src/__generated__/*', '#features/*': './src/features/*' } }),
      'src/features/code/fe/panel.ts': "import { id } from '#features/actions/fe/state.ts';\nimport { own } from './state.ts';\n",
      'src/features/code/fe/state.ts': 'export const own = 1;\n',
    });
    expect(problems(dir, 'cross-feature-imports')).toEqual(['src/features/code/fe/panel.ts:1: #features/actions/fe/state.ts']);
  });

  /**
   * A whole-pack rule, so its findings arrive as written with no span and its case needs a manifest: which module
   * is a contract is what `abuddy.json` says, not what a file looks like.
   */
  it('contract-leaves flags a contract leaf that reaches its own machine', () => {
    const dir = packWithImports({
      'abuddy.json': JSON.stringify({
        id: 'p', name: 'P', version: '1.0.0',
        features: [{ id: 'notes', plugin: { entry: 'src/features/notes/fe/plugin.ts', contract: 'src/features/notes/fe/contract.ts#Contract' } }],
      }),
      'src/features/notes/fe/contract.ts': "import type { Ctx } from './state.ts';\nexport type Contract = { state: Ctx };\n",
      'src/features/notes/fe/state.ts': "import { sendToPlugin } from '#generated/events.ts';\nexport type Ctx = { sent: typeof sendToPlugin };\n",
    });
    expect(problems(dir, 'contract-leaves')).toEqual(['src/features/notes/fe/contract.ts:1: ./state.ts']);
  });

  it('has a case for every rule it defines', () => {
    const covered = new Set<string>([...FIRES_ON_A_FILE.map(([key]) => key), ...Object.keys(FIRES_ELSEWHERE)]);
    expect(PACK_RULES.map((rule) => rule.key).filter((key) => !covered.has(key)),
      'a rule with no firing case is a gate nothing has watched fail').toEqual([]);
  });

  it('names a case that exists for each rule covered elsewhere', () => {
    const own = fs.readFileSync(fileURLToPath(import.meta.url), 'utf-8');
    // Either quote style: a title holding an apostrophe is written with double quotes, and a pointer check that
    // only matched single ones would report a case that is right there
    const declared = (title: string) => [`it('`, `it("`, `describe('`, `describe("`]
      .some((open) => own.includes(`${open}${title}${open.at(-1)}`));
    const gone = Object.entries(FIRES_ELSEWHERE)
      .filter(([, title]) => !declared(title))
      .map(([key, title]) => `${key} names "${title}", which is no case in this file`);
    expect(gone, 'a pointer to a case that no longer exists is the claim this table exists to avoid').toEqual([]);
  });
});

/**
 * The opt-out. Switchable means "a violation has no runtime effect", so the list of names a pack may write is
 * derived from the rules rather than repeated, and a name outside it is an error naming what is allowed —
 * a silent typo would leave a rule off for as long as nobody looked.
 */
describe('abuddy.checks.json', () => {
  const withChecks = (checks: string, code = "console.log('x');\n") => pack({
    'abuddy.checks.json': checks,
    'src/extensions/steps/x.ts': code,
  });

  it('silences a switchable rule the pack allows', () => {
    const dir = withChecks(JSON.stringify({ allow: ['backend-console'] }));
    expect(loadPackChecks(dir)).toEqual(new Set(['backend-console']));
    expect([...packRuleProblems(dir)]).toEqual([]);
  });

  it('reports the rule when the pack allows nothing', () => {
    expect(problems(withChecks(JSON.stringify({ allow: [] })), 'backend-console'))
      .toEqual(['src/extensions/steps/x.ts:1: console.log']);
  });

  it('refuses a rule that is not switchable, naming the ones that are', () => {
    expect(() => loadPackChecks(withChecks(JSON.stringify({ allow: ['host-imports'] }))))
      .toThrow(/"host-imports", which is not a rule a pack may switch off.*backend-console/s);
  });

  it('refuses a name that is no rule at all, and a file that is not a list', () => {
    expect(() => loadPackChecks(withChecks(JSON.stringify({ allow: ['no-console'] })))).toThrow(/not a rule a pack may switch off/);
    expect(() => loadPackChecks(withChecks(JSON.stringify({ allow: 'backend-console' })))).toThrow(/is a list of rule names/);
    expect(() => loadPackChecks(withChecks('{'))).toThrow(/does not parse/);
  });

  it('is optional: a pack without one allows nothing', () => {
    expect(loadPackChecks(pack({ 'src/f.ts': 'export const x = 1;\n' }))).toEqual(new Set());
  });
});

/** What `abuddy build` throws: every failing rule at once, and the paste-able line for the switchable ones */
describe('refusePackRuleViolations', () => {
  it('names every rule that fired, and how to allow the switchable one', () => {
    const dir = pack({
      'src/extensions/steps/x.ts': "import { edgeStore } from '@abuddy/host/ears';\nconsole.log('x');\n",
    });
    let message = '';
    try {
      refusePackRuleViolations(dir);
    } catch (err) {
      message = (err as Error).message;
    }
    expect(message).toContain('2 pack rules failed.');
    expect(message).toContain('src/extensions/steps/x.ts:1: @abuddy/host/ears');
    expect(message).toContain('src/extensions/steps/x.ts:2: console.log');
    expect(message).toContain('{ "allow": ["backend-console"] }');
    expect(message, 'a rule that is not switchable must not offer a way to allow it')
      .not.toContain('["host-imports"]');
  });

  it('returns for a pack with nothing to report', () => {
    expect(() => refusePackRuleViolations(pack({ 'src/f.ts': 'export const x = 1;\n' }))).not.toThrow();
  });
});

/**
 * One offence, one message. Several rules can be right about one import, and a pack author deleting one line
 * should be told the thing that matters about it — not the same line three times in three blocks.
 */
describe('when several rules are right about one site', () => {
  const offender = (code: string) => {
    const dir = pack({ 'package.json': JSON.stringify({ name: 'p', type: 'module' }), 'src/extensions/steps/x.ts': code });
    return [...packRuleProblems(dir)].map(([key, found]) => `${key}: ${found.join(' | ')}`);
  };

  it('reports the cause that comes first, and only that one', () => {
    // Three rules are right: @abuddy/host is not installed for a pack, `_rootEvents` is @internal, and it is
    // the raw transport. The import is unusable because the package is absent, so that is what is said about it;
    // `raw-transport` still names the identifier, which is a second thing to change rather than the same one.
    expect(offender("import { _rootEvents } from '@abuddy/host/bus';\n")).toEqual([
      'host-imports: src/extensions/steps/x.ts:1: @abuddy/host/bus',
      'raw-transport: src/extensions/steps/x.ts:1: _rootEvents',
    ]);
  });

  it('keeps two real offences that happen to share a line', () => {
    expect(offender("import { edgeStore } from '@abuddy/host/ears'; console.log('x');\n")).toEqual([
      'host-imports: src/extensions/steps/x.ts:1: @abuddy/host/ears',
      'backend-console: src/extensions/steps/x.ts:1: console.log',
    ]);
  });

  /**
   * The order in `PACK_RULES` *is* the precedence, so it is worth pinning: what stops the pack loading, then
   * what stops a specifier resolving, then what breaks on an app update, then the conventions.
   */
  it('declares that precedence in one place', () => {
    expect(PACK_RULES.map((rule) => rule.key)).toEqual([
      'source-resolution', 'contract-leaves',
      'host-imports', 'lmdb-imports',
      'own-modules', 'pack-own-aliases',
      'internal-package-imports',
      'untyped-sends', 'raw-transport', 'backend-console', 'cross-feature-imports',
    ]);
  });
});

/**
 * The line the failure prints is the file the reader reads. They drifted once — the advice named a `"checks"`
 * key the reader never looks for — so this pastes it rather than matching its text.
 */
it('allowLineWorks: pasting the line the error prints switches the rule off', () => {
  const dir = pack({ 'package.json': JSON.stringify({ name: 'p', type: 'module' }), 'src/extensions/steps/x.ts': "console.log('x');\n" });
  const printed = (() => { try { refusePackRuleViolations(dir); return ''; } catch (err) { return (err as Error).message; } })();
  const advice = printed.split('\n').find((line) => line.includes('abuddy.checks.json'));
  expect(advice).toBeDefined();
  const json = advice!.slice(advice!.indexOf('{'), advice!.lastIndexOf('}') + 1);
  fs.writeFileSync(path.join(dir, 'abuddy.checks.json'), json);
  expect(() => refusePackRuleViolations(dir)).not.toThrow();
});

/**
 * The one rule whose subject is not a file's text: what the pack's compiler resolves.
 *
 * The fixture installs a package shaped like `@abuddy/sdk` — an exports map with a source branch beside the
 * published one, `src/` and `dist/` both present — because that shape is the whole point: the branch is
 * unreachable for a real consumer and reachable for a linked checkout, and the rule is about which one this
 * pack's `tsc` picks.
 */
describe('source-resolution', () => {
  const withSdk = (tsconfig: Record<string, unknown>) => pack({
    'package.json': JSON.stringify({ name: 'p', type: 'module' }),
    'tsconfig.json': JSON.stringify({ compilerOptions: { module: 'esnext', moduleResolution: 'bundler', ...tsconfig } }),
    'node_modules/@abuddy/sdk/package.json': JSON.stringify({
      name: '@abuddy/sdk',
      exports: { '.': { '@abuddy/source': './src/index.ts', types: './dist/index.d.ts', default: './dist/index.js' } },
    }),
    'node_modules/@abuddy/sdk/src/index.ts': 'export const version = 1;\n',
    'node_modules/@abuddy/sdk/dist/index.d.ts': 'export declare const version: number;\n',
    'node_modules/@abuddy/sdk/dist/index.js': 'export const version = 1;\n',
    'src/system.ts': "import { version } from '@abuddy/sdk';\nexport const v = version;\n",
  });

  it('passes a pack that resolves the published dist', () => {
    expect(problems(withSdk({}), 'source-resolution')).toEqual([]);
  });

  it('refuses one whose tsconfig resolves a checkout\'s source, naming the file', () => {
    const found = problems(withSdk({ customConditions: ['@abuddy/source'] }), 'source-resolution');
    expect(found).toHaveLength(1);
    expect(found[0]).toContain('@abuddy/sdk -> node_modules/@abuddy/sdk/src/index.ts');
  });

  /** An `extends` chain is the route a rule that read the config text for `customConditions` would miss */
  it('refuses it through an extends chain too', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'tsconfig.base.json'), JSON.stringify({ compilerOptions: { customConditions: ['@abuddy/source'] } }));
    fs.writeFileSync(path.join(dir, 'tsconfig.json'), JSON.stringify({
      extends: './tsconfig.base.json',
      compilerOptions: { module: 'esnext', moduleResolution: 'bundler' },
    }));
    expect(problems(dir, 'source-resolution')).toHaveLength(1);
  });

  /**
   * A config the rule cannot read is reported, not passed over. The opposite — `[]` for a pack nobody looked
   * at — is the shape `findMissingSourceConditions` refuses for the repo's own configs, with the reason that a
   * rule which guesses is a rule that lets the next one through.
   */
  it('reports a tsconfig that does not parse, rather than passing', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'tsconfig.json'), '{ "compilerOptions": ');
    expect(problems(dir, 'source-resolution')).toEqual([expect.stringContaining('could not be read') as unknown as string]);
  });

  it('reports an extends naming a file that is not there', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'tsconfig.json'), JSON.stringify({ extends: './tsconfig.missing.json' }));
    const found = problems(dir, 'source-resolution');
    expect(found).toHaveLength(1);
    expect(found[0]).toMatch(/could not be read.*tsconfig\.missing\.json/);
  });

  /** The one diagnostic that is about the file set and not resolution, so it must not make this rule fire */
  it('says nothing about a pack whose include matches no file', () => {
    const dir = pack({
      'package.json': JSON.stringify({ name: 'p', type: 'module' }),
      'tsconfig.json': JSON.stringify({ compilerOptions: { module: 'esnext', moduleResolution: 'bundler' }, include: ['src/**/*.ts'] }),
    });
    expect(problems(dir, 'source-resolution')).toEqual([]);
  });

  /**
   * The other route to source, and the one `tsc` cannot be asked about: nothing resolves a Vitest config's
   * `resolve.conditions` until the run, by which time the pack's suite has passed against workspace source.
   */
  it("reports a pack's vitest config naming the condition", () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'vitest.config.ts'),
      "export default { resolve: { conditions: ['@abuddy/source'] } };\n");
    expect(problems(dir, 'source-resolution')).toEqual(['vitest.config.ts:1: @abuddy/source']);
  });

  /** A pattern over the pack root, so a JS config is not a hole an external pack can fall into */
  it('reports a JS config too, not only a .ts one', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'vitest.config.js'),
      "export default { resolve: { conditions: ['@abuddy/source'] } };\n");
    expect(problems(dir, 'source-resolution')).toEqual(['vitest.config.js:1: @abuddy/source']);
  });

  /** A string literal from the tree, not a text search, so a pack may still write about the condition */
  it('says nothing about a config that only mentions it in a comment', () => {
    const dir = withSdk({});
    fs.writeFileSync(path.join(dir, 'vitest.config.ts'),
      '// A pack declares no @abuddy/source condition: it resolves the published dist\nexport default {};\n');
    expect(problems(dir, 'source-resolution')).toEqual([]);
  });

  it('says nothing about a package the pack does not have', () => {
    expect(problems(pack({ 'package.json': '{"name":"p"}', 'tsconfig.json': '{}', 'src/x.ts': 'export const x = 1;\n' }), 'source-resolution')).toEqual([]);
  });
});
