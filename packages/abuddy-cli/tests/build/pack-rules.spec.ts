import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { loadPackChecks, packRuleProblems, PACK_RULES, refusePackRuleViolations, type PackRuleKey } from '../../src/build/pack-rules.ts';
import { resetSourceCache } from '../../src/build/pack-sources.ts';

/**
 * src/build/pack-rules.ts: the rules every pack is held to, which `abuddy build`, `abuddy validate` and
 * `abuddy test` run. The repo's own packs go through the same functions from
 * `scripts/check-import-specifiers.ts`; this is every other pack.
 */
const dirs: string[] = [];
afterEach(() => {
  for (const dir of dirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
  // The reader caches by path, and a temp tree reuses paths
  resetSourceCache();
});

/** A pack directory holding `files`, each written under it */
function pack(files: Record<string, string>): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'abuddy-pack-rules-'));
  dirs.push(dir);
  for (const [file, content] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, file)), { recursive: true });
    fs.writeFileSync(path.join(dir, file), content);
  }
  return dir;
}

/** One rule's findings, by key, over a pack's `src` */
const problems = (dir: string, key: PackRuleKey): string[] => packRuleProblems(dir).get(key) ?? [];

describe('internal-package-imports', () => {
  it.each([
    ['src/system.ts', "import { _getMediaPath } from '@abuddy/sdk/utils';\n", 'src/system.ts:1: _getMediaPath from @abuddy/sdk/utils'],
    ['src/probe.ts', "const { _seedHookRegistry } = await import('@abuddy/sdk/seed');\n", 'src/probe.ts:1: _seedHookRegistry from @abuddy/sdk/seed'],
    ['src/panel.vue', "<template><div /></template>\n<script setup lang=\"ts\">\nimport { _rootEvents as bus } from '@abuddy/sdk/runtime';\n</script>\n", 'src/panel.vue:3: _rootEvents from @abuddy/sdk/runtime'],
  ])('refuses %s', (file, content, problem) => {
    expect(problems(pack({ [file]: content }), 'internal-package-imports')).toEqual([problem]);
  });

  it('accepts public API, a pack-local underscore and the generated facades', () => {
    const dir = pack({
      'src/system.ts': [
        "import { importCompiledSeeds, getDataDirPath } from '@abuddy/sdk/utils';",
        "import { formatProviderError as _formatProviderError } from '@abuddy/sdk/actions';",
        "import { _fmt } from './_helpers/format.ts';",
        '',
      ].join('\n'),
      // Generated by the pack's own build, from the manifest: not the author's to fix
      'src/__generated__/events.ts': "import { _rootEvents } from '@abuddy/sdk/runtime';\n",
    });
    expect(problems(dir, 'internal-package-imports')).toEqual([]);
  });

  it('has nothing to say about a pack with no src', () => {
    expect([...packRuleProblems(pack({ 'abuddy.json': '{}' }))]).toEqual([]);
  });
});

/**
 * One firing example per rule, so none of them can land without a case that proves it bites — the same
 * property `check:specifiers`' own spec asserts for the repo's rules. The pack fixture carries the
 * `package.json` `imports` map that makes a `#` string a specifier rather than a colour.
 */
describe('every rule', () => {
  /** A pack with an imports map, a generated facade to resolve against, and whatever else the case writes */
  const packWithImports = (files: Record<string, string>) => pack({
    'package.json': JSON.stringify({ name: 'p', type: 'module', imports: { '#generated/*': './src/__generated__/*' } }),
    'src/__generated__/events.ts': 'export const sendToSystem = 1;\n',
    'src/sibling.ts': 'export const sibling = 1;\n',
    ...files,
  });

  it.each([
    ['own-modules', "import { sendToSystem } from '#generated/events';\n",
      "src/f.ts:1: '#generated/events' names no file — write '#generated/events.ts'"],
    // The `.js` form is this rule's too, not a second rule's: one offence, one message, and this one names the fix
    ['own-modules', "import { sibling } from './sibling.js';\n",
      "src/f.ts:1: './sibling.js' names no file — write './sibling.ts'"],
    ['pack-own-aliases', "import { x } from '@/features/notes/be/x.ts';\n", 'src/f.ts:1: @/features/notes/be/x.ts'],
    ['host-imports', "import { edgeStore } from '@abuddy/host/ears';\n", 'src/f.ts:1: @abuddy/host/ears'],
    ['lmdb-imports', "import { open } from 'lmdb';\n", 'src/f.ts:1: lmdb'],
    ['untyped-sends', "import { untypedSendToSystem } from '@abuddy/sdk/events';\n",
      'src/f.ts:1: untypedSendToSystem from @abuddy/sdk/events'],
    ['raw-transport', 'export const send = () => _rootEvents.emitOutgoing(event);\n', 'src/f.ts:1: _rootEvents'],
  ])('%s fires on an offending file', (key, code, problem) => {
    expect(problems(packWithImports({ 'src/f.ts': code }), key as PackRuleKey)).toEqual([problem]);
  });

  it('backend-console fires under a backend path and not under a frontend one', () => {
    const dir = packWithImports({
      'src/features/notes/be/system.ts': "console.log('x');\n",
      'src/features/notes/fe/state.ts': "console.log('x');\n",
    });
    expect(problems(dir, 'backend-console')).toEqual(['src/features/notes/be/system.ts:1: console.log']);
  });

  it('has a case above for every rule it defines', () => {
    const covered = new Set(['own-modules', 'pack-own-aliases', 'host-imports', 'lmdb-imports',
      'untyped-sends', 'raw-transport', 'backend-console', 'internal-package-imports']);
    expect(PACK_RULES.map((rule) => rule.key).filter((key) => !covered.has(key)),
      'a rule with no firing case is a gate nothing has watched fail').toEqual([]);
  });
});

/**
 * The opt-out. Switchable means "a violation has no runtime effect", so the list of names a pack may write is
 * derived from the rules rather than repeated, and a name outside it is an error naming what is allowed —
 * a silent typo would leave a rule off for as long as nobody looked.
 */
describe('abuddy.checks.json', () => {
  const withChecks = (checks: string, code = "console.log('x');\n") => pack({
    'abuddy.checks.json': checks,
    'src/extensions/steps/x.ts': code,
  });

  it('silences a switchable rule the pack allows', () => {
    const dir = withChecks(JSON.stringify({ allow: ['backend-console'] }));
    expect(loadPackChecks(dir)).toEqual(new Set(['backend-console']));
    expect([...packRuleProblems(dir)]).toEqual([]);
  });

  it('reports the rule when the pack allows nothing', () => {
    expect(problems(withChecks(JSON.stringify({ allow: [] })), 'backend-console'))
      .toEqual(['src/extensions/steps/x.ts:1: console.log']);
  });

  it('refuses a rule that is not switchable, naming the ones that are', () => {
    expect(() => loadPackChecks(withChecks(JSON.stringify({ allow: ['host-imports'] }))))
      .toThrow(/"host-imports", which is not a rule a pack may switch off.*backend-console/s);
  });

  it('refuses a name that is no rule at all, and a file that is not a list', () => {
    expect(() => loadPackChecks(withChecks(JSON.stringify({ allow: ['no-console'] })))).toThrow(/not a rule a pack may switch off/);
    expect(() => loadPackChecks(withChecks(JSON.stringify({ allow: 'backend-console' })))).toThrow(/is a list of rule names/);
    expect(() => loadPackChecks(withChecks('{'))).toThrow(/does not parse/);
  });

  it('is optional: a pack without one allows nothing', () => {
    expect(loadPackChecks(pack({ 'src/f.ts': 'export const x = 1;\n' }))).toEqual(new Set());
  });
});

/** What `abuddy build` throws: every failing rule at once, and the paste-able line for the switchable ones */
describe('refusePackRuleViolations', () => {
  it('names every rule that fired, and how to allow the switchable one', () => {
    const dir = pack({
      'src/extensions/steps/x.ts': "import { edgeStore } from '@abuddy/host/ears';\nconsole.log('x');\n",
    });
    let message = '';
    try {
      refusePackRuleViolations(dir);
    } catch (err) {
      message = (err as Error).message;
    }
    expect(message).toContain('2 pack rules failed.');
    expect(message).toContain('src/extensions/steps/x.ts:1: @abuddy/host/ears');
    expect(message).toContain('src/extensions/steps/x.ts:2: console.log');
    expect(message).toContain('"checks": { "allow": ["backend-console"] }');
    expect(message, 'a rule that is not switchable must not offer a way to allow it')
      .not.toContain('["host-imports"]');
  });

  it('returns for a pack with nothing to report', () => {
    expect(() => refusePackRuleViolations(pack({ 'src/f.ts': 'export const x = 1;\n' }))).not.toThrow();
  });
});
